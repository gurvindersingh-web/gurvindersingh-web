#!/usr/bin/env python3
"""
Writes assets/stats.svg from the GitHub REST API. Standard library only.

  GITHUB_TOKEN=$(gh auth token) python scripts/gen_stats.py     # real data (what the workflow runs)
  python scripts/gen_stats.py --seed                            # offline placeholder

Replaces the github-readme-stats / streak cards, which depend on a shared public
Vercel instance that is frequently rate limited.
"""
import json
import os
import sys
import urllib.request

from build_assets import DIM, FAINT, FS, GROUND, INK, LINE, MID, MONO, REDUCED, CW, esc, write

USER = os.environ.get("GH_USER", "gurvindersingh-web")
API = "https://api.github.com"


# ── data ────────────────────────────────────────────────────────────────
def get(path):
    req = urllib.request.Request(API + path, headers={
        "Accept": "application/vnd.github+json",
        "User-Agent": "profile-readme-stats",
        **({"Authorization": f"Bearer {os.environ['GITHUB_TOKEN']}"} if os.environ.get("GITHUB_TOKEN") else {}),
    })
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def collect(user=USER):
    profile = get(f"/users/{user}")
    repos, page = [], 1
    while True:
        chunk = get(f"/users/{user}/repos?per_page=100&type=owner&page={page}")
        repos += chunk
        if len(chunk) < 100:
            break
        page += 1
    own = [r for r in repos if not r["fork"]]
    langs, counts = {}, {}
    for r in own:
        for lang, n in get(f"/repos/{user}/{r['name']}/languages").items():
            langs[lang] = langs.get(lang, 0) + n
            counts[lang] = counts.get(lang, 0) + 1
    return {
        "repos": profile["public_repos"],
        "followers": profile["followers"],
        "stars": sum(r["stargazers_count"] for r in own),
        "langs": langs,
        "counts": counts,
    }


# ── render ──────────────────────────────────────────────────────────────
def size(n):
    return f"{n / 1_000_000:.1f} MB" if n >= 1_000_000 else f"{max(1, round(n / 1000))} KB"


def render(d):
    total = sum(d["langs"].values()) or 1
    ranked = sorted(d["langs"].items(), key=lambda kv: -kv[1])
    top, rest = ranked[:6], ranked[6:]
    rows = [(k, v, d["counts"][k]) for k, v in top]
    if rest:
        rows.append(("Other", sum(v for _, v in rest), None))

    W = 880
    y_sum, y_head, y0, pitch = 40, 82, 118, 26
    H = y0 + (len(rows) - 1) * pitch + 34
    bar_x, bar_w = 210, 360
    cols = {"share": 660, "size": 752, "repos": 832}

    el = [f'<text x="48" y="{y_sum}" fill="{INK}">{d["repos"]} public repositories, {d["followers"]} followers, {d["stars"]} stars received</text>']
    el.append(f'<text x="48" y="{y_head}" fill="{MID}">Language</text>')
    el.append(f'<text x="{bar_x}" y="{y_head}" fill="{MID}">Share of code, forks excluded</text>')
    for k, label in (("share", "Share"), ("size", "Size"), ("repos", "Repos")):
        el.append(f'<text x="{cols[k]}" y="{y_head}" text-anchor="end" fill="{MID}">{label}</text>')
    el.append(f'<rect x="48" y="{y_head + 12}" width="{W - 96}" height="1" fill="{LINE}"/>')

    for i, (name, n, c) in enumerate(rows):
        y = y0 + i * pitch
        share = n / total
        main = name != "Other"
        el.append(f'<text x="48" y="{y}" fill="{INK if main else DIM}">{esc(name)}</text>')
        el.append(f'<rect x="{bar_x}" y="{y - 9}" width="{bar_w}" height="8" fill="{FAINT}"/>')
        el.append(f'<rect class="bar" x="{bar_x}" y="{y - 9}" width="{max(2, share * bar_w):.1f}" height="8" fill="{INK if main else DIM}"/>')
        el.append(f'<text x="{cols["share"]}" y="{y}" text-anchor="end" fill="{INK if main else DIM}">{share * 100:.1f}%</text>')
        el.append(f'<text x="{cols["size"]}" y="{y}" text-anchor="end" fill="{DIM}">{size(n)}</text>')
        if c is not None:
            el.append(f'<text x="{cols["repos"]}" y="{y}" text-anchor="end" fill="{DIM}">{c}</text>')

    css = f"text{{font-family:{MONO};font-size:{FS}px}}\n{REDUCED}"
    write("stats.svg", f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-label="{d["repos"]} public repositories, {d["followers"]} followers, {d["stars"]} stars. Top languages: {esc(", ".join(f"{k} {v / total * 100:.0f}%" for k, v, _ in rows[:4]))}.">
<style>{css}</style>
<rect x=".5" y=".5" width="{W - 1}" height="{H - 1}" rx="6" fill="{GROUND}" stroke="{LINE}"/>
{"".join(el)}
</svg>
''')


def seed():
    W, H = 880, 104
    css = f"text{{font-family:{MONO};font-size:{FS}px}}"
    write("stats.svg", f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-label="Stats are generated by a workflow and have not run yet.">
<style>{css}</style>
<rect x=".5" y=".5" width="{W - 1}" height="{H - 1}" rx="6" fill="{GROUND}" stroke="{LINE}"/>
<text x="48" y="44" fill="{INK}">0 packets captured so far</text>
<text x="48" y="68" fill="{DIM}">The stats workflow runs on the first push, then refreshes daily.</text>
</svg>
''')


if __name__ == "__main__":
    seed() if "--seed" in sys.argv else render(collect())
